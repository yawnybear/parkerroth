// Bundles src/stylesheets/application.css into a single dist/application.css by inlining
// its local @import rules (recursively, in order), so a page needs one stylesheet request
// instead of a waterfall of ~20. Remote @imports (e.g. Optics' Noto web fonts, which this
// site doesn't use) are dropped. Source files stay as they are; run `npm run build:css`
// after editing them and commit the output.
const fs = require('fs')
const path = require('path')

const ENTRY = path.join(__dirname, '..', 'src', 'stylesheets', 'application.css')
const OUT = path.join(__dirname, '..', 'dist', 'application.css')
const IMPORT = /@import\s+(?:url\(\s*)?(['"])([^'"]+)\1\s*\)?\s*;/g

function inline(file, seen = new Set()) {
  const resolved = path.resolve(file)
  if (seen.has(resolved)) return ''
  seen.add(resolved)
  const css = fs.readFileSync(resolved, 'utf8')
  return css.replace(IMPORT, (_, __, href) => {
    if (/^(https?:)?\/\//.test(href)) return `/* dropped remote import: ${href} */`
    const target = path.resolve(path.dirname(resolved), href)
    const rel = path.relative(path.join(__dirname, '..'), target)
    return `/* ---- ${rel} ---- */\n${inline(target, seen)}`
  })
}

const banner = '/* Generated by scripts/build-css.js from src/stylesheets/application.css. Do not edit. */\n'
fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, banner + inline(ENTRY))
console.log('wrote', path.relative(process.cwd(), OUT), `(${Math.round(fs.statSync(OUT).size / 1024)} KB)`)
